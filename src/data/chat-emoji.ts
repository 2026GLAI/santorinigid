/**
 * Имя файла в наборе Twemoji: коды символа через дефис, шестнадцатерично.
 * Правило набора: служебный код FE0F (вариант отображения) опускается,
 * если в эмодзи нет склейки ZWJ (200D).
 */
export function twemojiFile(emoji: string): string {
  const codes = [...emoji].map((c) => c.codePointAt(0)!);
  const hasZwj = codes.includes(0x200d);
  return codes
    .filter((c) => hasZwj || c !== 0xfe0f)
    .map((c) => c.toString(16))
    .join('-');
}
