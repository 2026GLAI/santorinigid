export default {
  async fetch(request, env) {
    if (request.method === 'OPTIONS') {
      return new Response(null, { headers: corsFor(request) });
    }

    if (request.method !== 'POST') {
      return json({ error: 'Not found' }, 404, request);
    }

    // Ключ не задан — честно говорим об этом. Сайт в таком случае
    // сам вернётся к своей базе готовых ответов, гость ничего не заметит.
    if (!env.GROQ_API_KEY) {
      return json({ error: 'Ключ не настроен' }, 503, request);
    }

    let question;
    try {
      const body = await request.json();
      question = String(body.question || '').trim().slice(0, 500);
    } catch {
      return json({ error: 'Некорректный запрос' }, 400, request);
    }

    if (question.length < 2) {
      return json({ error: 'Слишком короткий вопрос' }, 400, request);
    }

    try {
      const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${env.GROQ_API_KEY}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: env.GROQ_MODEL || 'llama-3.3-70b-versatile',
          messages: [
            { role: 'system', content: SYSTEM_PROMPT },
            { role: 'user', content: question },
          ],
          // Низкая температура = меньше фантазии. Для сайта, где важны
          // факты, это важнее живости слога.
          temperature: 0.4,
          // Ответ должен помещаться в пузырёк чата на телефоне
          max_tokens: 400,
        }),
      });

      if (!res.ok) {
        // Сервис недоступен или лимит исчерпан — сайт вернётся к своей базе
        return json({ error: 'Сервис недоступен' }, 502, request);
      }

      const data = await res.json();
      const answer = data.choices?.[0]?.message?.content?.trim();

      if (!answer) return json({ error: 'Пустой ответ' }, 502, request);

      return json({ answer }, 200, request);
    } catch {
      return json({ error: 'Ошибка обращения к ИИ' }, 502, request);
    }
  },
};
