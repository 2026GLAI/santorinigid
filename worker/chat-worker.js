    // лимиты бесплатного тарифа Groq не кладут чат целиком.
    const keys = [env.GROQ_API_KEY_1, env.GROQ_API_KEY_2, env.GROQ_API_KEY_3, env.GROQ_API_KEY]
      .filter(Boolean);
