/** Кто имеет право обращаться. Чужим сайтам чат не отдаём. */
const ALLOWED_ORIGINS = [
  'https://santorinigid.com',
  'https://www.santorinigid.com',
  'https://2026glai.github.io',
];

function corsFor(request) {
  const origin = request.headers.get('Origin') || '';
  const allowed = ALLOWED_ORIGINS.includes(origin);
  return {
    'Access-Control-Allow-Origin': allowed ? origin : ALLOWED_ORIGINS[0],
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    Vary: 'Origin',
  };
}

const json = (data, status, request) =>
  new Response(JSON.stringify(data), {
    status,
    headers: { 'Content-Type': 'application/json; charset=utf-8', ...corsFor(request) },
  });

